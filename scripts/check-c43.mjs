// JUDGE · C43 (E2, "aditividad"): runs the judge's suite exactly as it was at a commit (default 166332f, the main of G1):
// tests/conformance, playwright.conformance.config.ts and scripts/check-*.mjs, byte for byte, against the CURRENT
// working tree. The frozen copy is extracted with `git archive` to a folder outside the repo; Playwright runs with the
// repo as working directory (coder modules, greps and the next servers come from the tree under test) and resolves
// @playwright/test through a junction to the repo's node_modules.
//
//   node scripts/check-c43.mjs [--ref 166332f] [--out <dir>] [--skip-scripts] [-- <playwright args>]
//
// Steps: (1) frozen check-spike.mjs and `check-assets.mjs clean-channels` (unless --skip-scripts); (2) the frozen
// Playwright suite (every project of that config). Exit code: 0 only if every step passed.
import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const repo = process.cwd();
const argv = process.argv.slice(2);
const dash = argv.indexOf("--");
const own = dash >= 0 ? argv.slice(0, dash) : argv;
const passThrough = dash >= 0 ? argv.slice(dash + 1) : [];
const option = (name, fallback) => {
  const i = own.indexOf(name);
  return i >= 0 ? own[i + 1] : fallback;
};
const ref = option("--ref", "166332f");
const out = path.resolve(option("--out", path.join(os.tmpdir(), `iberapp-c43-${ref}`)));

if (!fs.existsSync(path.join(repo, "playwright.conformance.config.ts"))) {
  console.error("Correr desde la raíz de iberapp-games.");
  process.exit(2);
}

// 1. Frozen copy.
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
const tar = path.join(out, "suite.tar");
execFileSync("git", ["archive", "--format=tar", "-o", tar, ref, "tests/conformance", "playwright.conformance.config.ts", "scripts"], { cwd: repo, stdio: "inherit" });
// Relative name with cwd = out: GNU tar (Git Bash) would read "C:\…" as a remote host.
execFileSync("tar", ["-xf", "suite.tar"], { cwd: out, stdio: "inherit" });
fs.rmSync(tar);
fs.symlinkSync(path.join(repo, "node_modules"), path.join(out, "node_modules"), "junction");
const frozenFiles = execFileSync("git", ["ls-tree", "-r", "--name-only", ref, "tests/conformance", "playwright.conformance.config.ts", "scripts"], { cwd: repo, encoding: "utf8" })
  .split("\n")
  .filter(Boolean);
console.log(`C43 · suite de ${ref}: ${frozenFiles.length} archivos en ${out}`);

// Wrapper config: the frozen config as is, with the web servers started in the repo and the output kept in `out`.
fs.writeFileSync(
  path.join(out, "c43.config.ts"),
  `// Generated by scripts/check-c43.mjs: the frozen config of ${ref}, servers started in the tree under test.
import base from "./playwright.conformance.config";
const servers = base.webServer === undefined ? [] : Array.isArray(base.webServer) ? base.webServer : [base.webServer];
export default {
  ...base,
  outputDir: "./results",
  reporter: [["list"], ["json", { outputFile: "./results.json" }]],
  webServer: servers.map((s) => ({ ...s, cwd: ${JSON.stringify(repo)} })),
};
`,
);

const results = [];
const step = (name, command, args) => {
  console.log(`\nC43 · ${name}: ${command} ${args.join(" ")}`);
  const r = spawnSync(command, args, { cwd: repo, stdio: "inherit", env: process.env });
  results.push({ name, code: r.status ?? 1 });
};

// 2. Frozen scripts.
if (!own.includes("--skip-scripts")) {
  step("check-spike (congelado)", process.execPath, [path.join(out, "scripts", "check-spike.mjs")]);
  step("check-assets clean-channels (congelado)", process.execPath, [path.join(out, "scripts", "check-assets.mjs"), "clean-channels"]);
}

// 3. Frozen Playwright suite.
step("suite de Playwright (congelada)", process.execPath, [path.join(repo, "node_modules", "@playwright", "test", "cli.js"), "test", "-c", path.join(out, "c43.config.ts"), ...passThrough]);

console.log("\nC43 · resumen");
for (const r of results) console.log(`  ${r.code === 0 ? "OK   " : "FALLA"} ${r.name} (salida ${r.code})`);
process.exit(results.every((r) => r.code === 0) ? 0 : 1);
